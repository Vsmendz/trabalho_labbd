CREATE DATABASE frota;
USE frota;

CREATE TABLE VEICULO (
    PLACA VARCHAR(10) PRIMARY KEY,
    MODELO VARCHAR(50) NOT NULL,
    ANO INT NOT NULL,
    QUILOMETRAGEM_ATUAL DOUBLE NOT NULL,
    STATUS_VEICULO VARCHAR(20) NOT NULL,
    TIPO VARCHAR(20) NOT NULL,

    CONSTRAINT CK_VEICULO_ANO
        CHECK (ANO >= 1950),

    CONSTRAINT CK_VEICULO_KM
        CHECK (QUILOMETRAGEM_ATUAL >= 0),

    CONSTRAINT CK_VEICULO_STATUS
        CHECK (
            STATUS_VEICULO IN (
                'DISPONIVEL',
                'EM_ROTA',
                'MANUTENCAO'
            )
        ),

    CONSTRAINT CK_VEICULO_TIPO
        CHECK (
            TIPO IN (
                'CARRO',
                'VAN',
                'CAMINHAO'
            )
        )
);

CREATE TABLE MOTORISTA (
    CPF CHAR(11) PRIMARY KEY,
    NOME VARCHAR(100) NOT NULL,
    CATEGORIA_CNH CHAR(1) NOT NULL,

    CONSTRAINT CK_MOTORISTA_CNH
        CHECK (
            CATEGORIA_CNH IN (
                'B',
                'C',
                'D',
                'E'
            )
        )
);

CREATE TABLE VIAGEM (
    ID INT AUTO_INCREMENT PRIMARY KEY,

    DATA_SAIDA TIMESTAMP NOT NULL,
    DATA_CHEGADA TIMESTAMP NULL,

    KM_INICIAL DOUBLE NOT NULL,
    KM_FINAL DOUBLE NULL,

    PLACA_VEICULO VARCHAR(10) NOT NULL,
    CPF_MOTORISTA CHAR(11) NOT NULL,

    CONSTRAINT CK_VIAGEM_KM_INICIAL
        CHECK (KM_INICIAL >= 0),

    CONSTRAINT CK_VIAGEM_KM_FINAL
        CHECK (
            KM_FINAL IS NULL
            OR KM_FINAL >= KM_INICIAL
        ),

    FOREIGN KEY (PLACA_VEICULO)
        REFERENCES VEICULO (PLACA),

    FOREIGN KEY (CPF_MOTORISTA)
        REFERENCES MOTORISTA (CPF)
);

CREATE TABLE MANUTENCAO (
    ID INT AUTO_INCREMENT PRIMARY KEY,
    DESCRICAO VARCHAR(100) NOT NULL,
    KM_REFERENCIA DOUBLE NOT NULL,

    CONSTRAINT CK_MANUTENCAO_KM
        CHECK (KM_REFERENCIA > 0)
);

CREATE TABLE MANUTENCAO_VEICULO (
    ID INT AUTO_INCREMENT PRIMARY KEY,

    PLACA_VEICULO VARCHAR(10) NOT NULL,
    ID_MANUTENCAO INT NOT NULL,

    DATA_GERACAO DATETIME DEFAULT CURRENT_TIMESTAMP,

    DATA_MANUTENCAO DATE NULL,

    KM_FEITO DOUBLE NULL,

    STATUS VARCHAR(20) DEFAULT 'PENDENTE',

    OBSERVACAO VARCHAR(255) NULL,

    CONSTRAINT CK_MANUT_STATUS
        CHECK (
            STATUS IN (
                'PENDENTE',
                'EM_ANDAMENTO',
                'REALIZADA',
                'CANCELADA'
            )
        ),

    CONSTRAINT CK_MANUT_KM
        CHECK (
            KM_FEITO IS NULL
            OR KM_FEITO >= 0
        ),

    FOREIGN KEY (PLACA_VEICULO)
        REFERENCES VEICULO(PLACA),

    FOREIGN KEY (ID_MANUTENCAO)
        REFERENCES MANUTENCAO(ID)
);