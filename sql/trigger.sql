USE frota;

DELIMITER $$

CREATE TRIGGER TRG_VALIDA_CNH
BEFORE INSERT ON VIAGEM
FOR EACH ROW
BEGIN

    DECLARE V_TIPO VARCHAR(20);
    DECLARE V_CATEGORIA CHAR(1);

    SELECT TIPO
    INTO V_TIPO
    FROM VEICULO
    WHERE PLACA = NEW.PLACA_VEICULO;

    SELECT CATEGORIA_CNH
    INTO V_CATEGORIA
    FROM MOTORISTA
    WHERE CPF = NEW.CPF_MOTORISTA;

    IF V_TIPO = 'CAMINHAO'
       AND V_CATEGORIA = 'B'
    THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT =
        'MOTORISTA COM CNH B NAO PODE DIRIGIR CAMINHAO';
    END IF;

END $$

CREATE TRIGGER TRG_ALERTA_MANUTENCAO
AFTER UPDATE ON VEICULO
FOR EACH ROW
BEGIN
    DECLARE V_ID_TIPO INT;
    
    SELECT ID INTO V_ID_TIPO 
    FROM MANUTENCAO 
    WHERE KM_REFERENCIA = 10000 
    LIMIT 1;
    
    IF NEW.QUILOMETRAGEM_ATUAL >= 10000
       AND FLOOR(OLD.QUILOMETRAGEM_ATUAL / 10000)
           < FLOOR(NEW.QUILOMETRAGEM_ATUAL / 10000)
    THEN
        INSERT INTO ALERTA_MANUTENCAO (
            MENSAGEM,
            PLACA_VEICULO,
            ID_TIPO_MANUTENCAO,
            STATUS_MANUTENCAO
        )
        VALUES (
            CONCAT('VEICULO ATINGIU ', 
                   FLOOR(NEW.QUILOMETRAGEM_ATUAL / 10000) * 10000, 
                   ' KM - MANUTENCAO PREVENTIVA NECESSARIA'),
            NEW.PLACA,
            V_ID_TIPO,
            'PENDENTE'
        );
    END IF;

END $$

DELIMITER ;