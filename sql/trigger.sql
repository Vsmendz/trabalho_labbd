USE frota;

DELIMITER $$

CREATE TRIGGER TRG_VALIDA_CNH
BEFORE INSERT ON VIAGEM
FOR EACH ROW
BEGIN

    DECLARE V_TIPO VARCHAR(20);
    DECLARE V_CATEGORIA CHAR(1);

    SELECT TIPO
    INTO V_TIPO
    FROM VEICULO
    WHERE PLACA = NEW.PLACA_VEICULO;

    SELECT CATEGORIA_CNH
    INTO V_CATEGORIA
    FROM MOTORISTA
    WHERE CPF = NEW.CPF_MOTORISTA;

    IF V_TIPO = 'CAMINHAO'
       AND V_CATEGORIA = 'B'
    THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT =
        'MOTORISTA COM CNH B NAO PODE DIRIGIR CAMINHAO';
    END IF;

END $$

DELIMITER $$

CREATE TRIGGER TRG_ALERTA_MANUTENCAO
AFTER UPDATE ON VEICULO
FOR EACH ROW
BEGIN
    -- O INSERT ... SELECT varre a tabela MANUTENCAO automaticamente
    INSERT INTO MANUTENCAO_VEICULO (
        PLACA_VEICULO,
        ID_MANUTENCAO,
        DATA_MANUTENCAO,
        KM_FEITO,
        STATUS,
        OBSERVACAO
    )
    SELECT
        NEW.PLACA,
        ID,
        NULL,
        NULL,
        'PENDENTE',
        CONCAT(
                'Manutenção preventiva necessária aos ',
                FLOOR(NEW.QUILOMETRAGEM_ATUAL / KM_REFERENCIA) * KM_REFERENCIA,
                ' km.'
        )
    FROM MANUTENCAO
    -- A condição abaixo é testada para CADA linha da tabela MANUTENCAO
    WHERE NEW.QUILOMETRAGEM_ATUAL >= KM_REFERENCIA
      AND FLOOR(OLD.QUILOMETRAGEM_ATUAL / KM_REFERENCIA) < FLOOR(NEW.QUILOMETRAGEM_ATUAL / KM_REFERENCIA);

END $$

DELIMITER ;