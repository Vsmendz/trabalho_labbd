USE frota;

DELIMITER $$

CREATE PROCEDURE ENCERRAR_VIAGEM (
    IN P_ID_VIAGEM INT,
    IN P_KM_FINAL INT
)
BEGIN

    DECLARE V_KM_INICIAL INT;
    DECLARE V_PLACA VARCHAR(10);

    START TRANSACTION;

    SELECT
        KM_INICIAL,
        PLACA_VEICULO
    INTO
        V_KM_INICIAL,
        V_PLACA
    FROM VIAGEM
    WHERE ID = P_ID_VIAGEM;

    IF P_KM_FINAL < V_KM_INICIAL THEN

        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT =
        'KM FINAL NAO PODE SER MENOR QUE O KM INICIAL';

    END IF;

    UPDATE VIAGEM
    SET
        KM_FINAL = P_KM_FINAL,
        DATA_CHEGADA = NOW()
    WHERE ID = P_ID_VIAGEM;

    UPDATE VEICULO
    SET
        QUILOMETRAGEM_ATUAL = P_KM_FINAL,
        STATUS_VEICULO = 'DISPONIVEL'
    WHERE PLACA = V_PLACA;

    COMMIT;

END $$

DELIMITER ;