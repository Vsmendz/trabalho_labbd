USE frota;

DELIMITER $$

DROP PROCEDURE IF EXISTS ENCERRAR_VIAGEM $$

CREATE PROCEDURE ENCERRAR_VIAGEM (
    IN P_ID_VIAGEM INT,
    IN P_KM_FINAL INT,
    IN P_OBSERVACAO VARCHAR(255)   -- opcional
)
BEGIN
    DECLARE V_KM_INICIAL INT;
    DECLARE V_PLACA VARCHAR(10);

    START TRANSACTION;

    SELECT KM_INICIAL, PLACA_VEICULO
    INTO V_KM_INICIAL, V_PLACA
    FROM VIAGEM
    WHERE ID = P_ID_VIAGEM;

    IF P_KM_FINAL < V_KM_INICIAL THEN
        SIGNAL SQLSTATE '45000'
        SET MESSAGE_TEXT = 'KM FINAL NAO PODE SER MENOR QUE O KM INICIAL';
    END IF;

    UPDATE VIAGEM
    SET
        KM_FINAL = P_KM_FINAL,
        DATA_CHEGADA = NOW(),
        STATUS = 'FINALIZADA',
        OBSERVACAO = COALESCE(P_OBSERVACAO, OBSERVACAO)
    WHERE ID = P_ID_VIAGEM;

    UPDATE VEICULO
    SET
        QUILOMETRAGEM_ATUAL = P_KM_FINAL,
        STATUS_VEICULO = 'DISPONIVEL'
    WHERE PLACA = V_PLACA;

    COMMIT;
END $$

DELIMITER ;

DELIMITER $$

CREATE PROCEDURE REGISTRAR_MANUTENCAO (
    IN P_PLACA VARCHAR(10),
    IN P_ID_MANUTENCAO INT,
    IN P_KM_FEITO DOUBLE
)
BEGIN

    UPDATE MANUTENCAO_VEICULO
    SET
        DATA_MANUTENCAO = CURDATE(),
        KM_FEITO = P_KM_FEITO,
        STATUS = 'REALIZADA'
    WHERE
        PLACA_VEICULO = P_PLACA
        AND ID_MANUTENCAO = P_ID_MANUTENCAO
        AND STATUS = 'PENDENTE'
    ORDER BY ID
    LIMIT 1;

END $$

DELIMITER ;

CALL ENCERRAR_VIAGEM(1, 15000, 'Chegada no destino com atraso');